/**
 * ASYCUDA World SAD XML builder (EXPERIMENTAL, profile `ge`).
 * Structure follows the UNCTAD ASYCUDA World SAD XML layout (one declaration, many <Item>).
 * Georgian national specifics are [UNVERIFIED]; see profiles/ge.ts and docs/xml-mapping.md.
 */
import { create } from "xmlbuilder2";
import type { XMLBuilder } from "xmlbuilder2/lib/interfaces";
import type { DeclarationModel } from "../model";
import { GE_PROFILE_VERSION, GE_TAX_CODES } from "./profiles/ge";

const nil = "<null>";
function el(parent: XMLBuilder, name: string, value?: string | number | null): XMLBuilder {
  const node = parent.ele(name);
  if (value === undefined || value === null || value === "") node.txt(nil);
  else node.txt(String(value));
  return node;
}

export function buildSadXml(model: DeclarationModel): string {
  const d = model.declaration;
  const doc = create({ version: "1.0", encoding: "UTF-8" });
  const root = doc.ele("ASYCUDA", { id: d.reference });
  root.com(` Generated by Customs Copilot GE — profile ${GE_PROFILE_VERSION} — EXPERIMENTAL${model.validatedAgainstRealSample ? "" : " (not validated against a real eCustoms sample)"} — ${model.generatedAt} `);

  const assessment = root.ele("Assessment_notice");
  el(assessment, "Item_tax_total");
  const prop = root.ele("Property");
  el(prop, "Sad_flow", "I");
  const forms = prop.ele("Forms");
  el(forms, "Number_of_the_form", 1);
  el(forms, "Total_number_of_forms", 1 + Math.max(0, Math.ceil((d.items.length - 1) / 3)));
  const nbers = prop.ele("Nbers");
  el(nbers, "Number_of_loading_lists", 0);
  el(nbers, "Total_number_of_items", d.totalItems);
  el(nbers, "Total_number_of_packages", d.totalPackages);
  el(prop, "Place_of_declaration", d.officeName);
  el(prop, "Selected_page", 1);

  const ident = root.ele("Identification");
  const office = ident.ele("Office_segment");
  el(office, "Customs_clearance_office_code", d.officeCode);
  el(office, "Customs_Clearance_office_name", d.officeName);
  const type = ident.ele("Type");
  el(type, "Type_of_declaration", d.type);
  el(type, "Declaration_gen_procedure_code", d.procedure.slice(0, 1));
  el(type, "Type_of_transit_document");
  el(ident, "Manifest_reference_number");
  const reg = ident.ele("Registration");
  el(reg, "Serial_number");
  el(reg, "Number");
  el(reg, "Date", d.registrationDate);
  const asmt = ident.ele("Assessment");
  el(asmt, "Serial_number");
  el(asmt, "Number");
  el(asmt, "Date");
  const receipt = ident.ele("receipt");
  el(receipt, "Serial_number");
  el(receipt, "Number");
  el(receipt, "Date");

  const traders = root.ele("Traders");
  const exporter = traders.ele("Exporter");
  el(exporter, "Exporter_code");
  el(exporter, "Exporter_name", [d.exporterName, d.exporterAddress, d.exporterCountry].filter(Boolean).join("\n"));
  const consignee = traders.ele("Consignee");
  el(consignee, "Consignee_code", d.consigneeTaxId);
  el(consignee, "Consignee_name", d.consigneeName);
  const financial = traders.ele("Financial");
  el(financial, "Financial_code", d.consigneeTaxId);
  el(financial, "Financial_name", d.consigneeName);

  const declarant = root.ele("Declarant");
  el(declarant, "Declarant_code", d.declarantTaxId);
  el(declarant, "Declarant_name", [d.declarantName, d.declarantAddress].filter(Boolean).join("\n"));
  el(declarant, "Declarant_representative");
  const ref = declarant.ele("Reference");
  el(ref, "Number", d.reference);

  const gi = root.ele("General_information");
  const country = gi.ele("Country");
  el(country, "Country_first_destination", "GE");
  el(country, "Trading_country", d.tradingCountry ?? d.dispatchCountry);
  const exp = country.ele("Export");
  el(exp, "Export_country_code", d.dispatchCountry);
  el(exp, "Export_country_name");
  el(exp, "Export_country_region");
  const dest = country.ele("Destination");
  el(dest, "Destination_country_code", "GE");
  el(dest, "Destination_country_name", "Georgia");
  el(dest, "Destination_country_region");
  el(country, "Country_of_origin_name", d.originCountry);
  el(gi, "Value_details");
  el(gi, "CAP");
  el(gi, "Additional_information", d.preArrival ? "PRE-ARRIVAL DECLARATION" : null);
  el(gi, "Comments_free_text", `Customs Copilot GE ${GE_PROFILE_VERSION}`);
  el(gi, "Total_invoice", d.invoiceTotalGel);
  el(gi, "Total_cost", d.freightGel);
  el(gi, "Total_CIF", d.customsValueGel);

  const transport = root.ele("Transport");
  const mot = transport.ele("Means_of_transport");
  const dai = mot.ele("Departure_arrival_information");
  el(dai, "Identity", d.transportIdentity);
  el(dai, "Nationality");
  const bi = mot.ele("Border_information");
  el(bi, "Identity", d.transportIdentity);
  el(bi, "Nationality");
  el(bi, "Mode", d.transportMode);
  el(mot, "Inland_mode_of_transport", d.transportMode);
  el(transport, "Container_flag", 0);
  const dt = transport.ele("Delivery_terms");
  el(dt, "Code", d.incoterm);
  el(dt, "Place", d.incotermPlace);
  el(dt, "Situation");
  const bo = transport.ele("Border_office");
  el(bo, "Code", d.borderOffice);
  el(bo, "Name");
  const pol = transport.ele("Place_of_loading");
  el(pol, "Code");
  el(pol, "Name", d.incotermPlace);
  el(pol, "Country", d.dispatchCountry);
  el(transport, "Location_of_goods", d.officeName);

  const fin = root.ele("Financial");
  const ft = fin.ele("Financial_transaction");
  el(ft, "Code1", 1);
  el(ft, "Code2", 1);
  const bank = fin.ele("Bank");
  el(bank, "Code");
  el(bank, "Name");
  el(bank, "Branch");
  el(bank, "Reference");
  const terms = fin.ele("Terms");
  el(terms, "Code");
  el(terms, "Description");
  el(fin, "Total_fees", d.feeGel);
  el(fin, "Total_taxes", (Number(d.dutyTotalGel) + Number(d.exciseTotalGel) + Number(d.vatTotalGel)).toFixed(2));
  el(fin, "Amount_to_be_paid", d.totalPayableGel);
  el(fin, "Mode_of_payment");
  el(fin, "Deffered_payment_reference");
  const guarantee = fin.ele("Guarantee");
  el(guarantee, "Name");
  el(guarantee, "Amount");
  el(guarantee, "Date");
  el(guarantee, "Excess_amount");

  const wh = root.ele("Warehouse");
  el(wh, "Identification");
  el(wh, "Delay");

  const val = root.ele("Valuation");
  el(val, "Calculation_working_mode", 1);
  const w = val.ele("Weight");
  el(w, "Gross_weight", d.grossWeightKg);
  const tot = val.ele("Total");
  el(tot, "Total_invoice", d.invoiceTotalGel);
  el(tot, "Total_weight", d.grossWeightKg);
  const gsInv = val.ele("Gs_Invoice");
  el(gsInv, "Amount_national_currency", d.invoiceTotalGel);
  el(gsInv, "Amount_foreign_currency", d.invoiceTotal);
  el(gsInv, "Currency_code", d.invoiceCurrency);
  el(gsInv, "Currency_name");
  el(gsInv, "Currency_rate", model.fx.rate);
  const gsFr = val.ele("Gs_external_freight");
  el(gsFr, "Amount_national_currency", d.freightGel);
  el(gsFr, "Amount_foreign_currency", d.freightGel);
  el(gsFr, "Currency_code", "GEL");
  el(gsFr, "Currency_name");
  el(gsFr, "Currency_rate", "1");
  const gsIn = val.ele("Gs_insurance");
  el(gsIn, "Amount_national_currency", d.insuranceGel);
  el(gsIn, "Amount_foreign_currency", d.insuranceGel);
  el(gsIn, "Currency_code", "GEL");
  el(gsIn, "Currency_name");
  el(gsIn, "Currency_rate", "1");
  const gsOt = val.ele("Gs_other_cost");
  el(gsOt, "Amount_national_currency", d.otherGel);
  el(gsOt, "Amount_foreign_currency", d.otherGel);
  el(gsOt, "Currency_code", "GEL");
  el(gsOt, "Currency_name");
  el(gsOt, "Currency_rate", "1");
  const gsDed = val.ele("Gs_deduction");
  el(gsDed, "Amount_national_currency", "0.00");
  el(gsDed, "Amount_foreign_currency", "0.00");
  el(gsDed, "Currency_code", "GEL");
  el(gsDed, "Currency_name");
  el(gsDed, "Currency_rate", "1");
  el(val, "Total_cost", d.freightGel);
  el(val, "Total_CIF", d.customsValueGel);

  for (const it of d.items) {
    const item = root.ele("Item");
    const sd = item.ele("Suppliers_documents");
    el(sd, "Suppliers_document_code");
    for (const doc of it.attachedDocs) {
      const ad = item.ele("Attached_documents");
      el(ad, "Attached_document_code", doc.code);
      el(ad, "Attached_document_name", doc.name);
      el(ad, "Attached_document_reference", doc.reference);
      el(ad, "Attached_document_from_rule", 0);
      el(ad, "Attached_document_date");
    }
    const pk = item.ele("Packages");
    el(pk, "Number_of_packages", it.packages);
    el(pk, "Marks1_of_packages", "N/M");
    el(pk, "Marks2_of_packages");
    el(pk, "Kind_of_packages_code", "PK");
    el(pk, "Kind_of_packages_name", "Package");
    const inco = item.ele("IncoTerms");
    el(inco, "Code", d.incoterm);
    el(inco, "Place", d.incotermPlace);
    const tar = item.ele("Tarification");
    const hs = tar.ele("HScode");
    el(hs, "Commodity_code", it.hsCode.slice(0, 8));
    el(hs, "Precision_1", it.hsCode.slice(8, 10));
    el(hs, "Precision_2");
    el(hs, "Precision_3");
    el(hs, "Precision_4");
    el(tar, "Preference_code");
    el(tar, "Extended_customs_procedure", d.procedure);
    el(tar, "National_customs_procedure", "000");
    el(tar, "Quota");
    el(tar, "Item_price", it.invoiceValue);
    el(tar, "Valuation_method_code", 1);
    el(tar, "Value_item", it.customsValueGel);
    el(tar, "Attached_doc_item");
    el(tar, "A.I._code");
    const su = tar.ele("Supplementary_unit");
    el(su, "Suppplementary_unit_code", it.unit);
    el(su, "Suppplementary_unit_name", it.unit);
    el(su, "Suppplementary_unit_quantity", it.quantity);
    el(tar, "Market_valuer");
    const gd = item.ele("Goods_description");
    el(gd, "Country_of_origin_code", it.originCountry);
    el(gd, "Description_of_goods", it.descriptionKa);
    el(gd, "Commercial_Description", it.descriptionRaw);
    const pd = item.ele("Previous_doc");
    el(pd, "Summary_declaration");
    el(pd, "Summary_declaration_sl");
    el(pd, "Previous_document_reference");
    el(pd, "Previous_warehouse_code");
    el(item, "Licence_number");
    el(item, "Free_text_1");
    el(item, "Free_text_2");
    const tax = item.ele("Taxation");
    el(tax, "Item_taxes_amount", it.totalGel);
    el(tax, "Item_taxes_guaranted_amount", "0.00");
    el(tax, "Item_taxes_mode_of_payment", 1);
    el(tax, "Counter_of_normal_mode_of_payment", 3);
    el(tax, "Displayed_item_taxes_amount", it.totalGel);
    const lines: [string, string, string, string, string][] = [
      [GE_TAX_CODES.duty, "Import duty", it.customsValueGel, it.dutyRate, it.dutyGel],
      [GE_TAX_CODES.excise, "Excise", it.customsValueGel, "", it.exciseGel],
      [GE_TAX_CODES.vat, "VAT", (Number(it.customsValueGel) + Number(it.dutyGel) + Number(it.exciseGel)).toFixed(2), "18", it.vatGel],
    ];
    for (const [code, desc, base, rate, amount] of lines) {
      const tl = tax.ele("Taxation_line");
      el(tl, "Tax_code", code);
      el(tl, "Tax_description", desc);
      el(tl, "Tax_base", base);
      el(tl, "Tax_rate", rate);
      el(tl, "Tax_amount", amount);
      el(tl, "Tax_MP", 1);
      el(tl, "Tax_Type_code");
    }
    const vi = item.ele("Valuation_item");
    const wi = vi.ele("Weight_itm");
    el(wi, "Gross_weight_itm", it.grossWeightKg);
    el(wi, "Net_weight_itm", it.netWeightKg);
    el(vi, "Total_cost_itm", it.freightGel);
    el(vi, "Total_CIF_itm", it.customsValueGel);
    el(vi, "Rate_of_adjustement", 0);
    el(vi, "Statistical_value", it.customsValueGel);
    el(vi, "Alpha_coeficient_of_apportionment");
    const ii = vi.ele("Item_Invoice");
    el(ii, "Amount_national_currency", it.invoiceValueGel);
    el(ii, "Amount_foreign_currency", it.invoiceValue);
    el(ii, "Currency_code", it.invoiceCurrency);
    el(ii, "Currency_name");
    el(ii, "Currency_rate", model.fx.rate);
    for (const [name, amt] of [
      ["internal_freight", "0.00"],
      ["external_freight", it.freightGel],
      ["insurance", it.insuranceGel],
      ["other_cost", it.otherGel],
      ["deduction", "0.00"],
    ] as const) {
      const n = vi.ele(name);
      el(n, "Amount_national_currency", amt);
      el(n, "Amount_foreign_currency", amt);
      el(n, "Currency_code", "GEL");
      el(n, "Currency_name");
      el(n, "Currency_rate", "1");
    }
    el(vi, "Market_valuer");
  }

  return doc.end({ prettyPrint: true });
}
